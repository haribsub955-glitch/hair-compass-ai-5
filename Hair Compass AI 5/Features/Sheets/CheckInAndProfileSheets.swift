    @MainActor
    private func analyzeProduct() async {
        guard purchaseManager.hasPremiumAccess else {
            analysisErrorMessage = "Hair Compass Pro is required for AI product analysis."
            return
        }

        let trimmedKey = openAIAPIKey.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmedKey.isEmpty else { return }

        isAnalyzingProduct = true
        analysisErrorMessage = ""

        defer { isAnalyzingProduct = false }

        do {
            productAnalysis = try await OpenAIRoutineProductAnalysisService(apiKey: trimmedKey).analyze(
                title: title,
                itemType: itemType.rawValue,
                category: category,
                notes: detail,
                image: productPhoto,
                profile: profile
            )
        } catch {
            analysisErrorMessage = error.localizedDescription
        }
    }

    private func saveProductPhotoIfNeeded() -> String {
        guard let productPhoto else { return "" }
        do {
            return try PhotoFileStore.shared.save(image: productPhoto)
        } catch {
            return ""
        }
    }
