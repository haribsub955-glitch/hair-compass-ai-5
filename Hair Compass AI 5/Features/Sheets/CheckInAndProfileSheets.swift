    private func saveCheckIn() {
        HapticHelper.success()
        let observation = dailyObservation(for: date)
        let entry = CheckInEntry(
            date: date,
            scalpScore: Int(scalpScore.rounded()),
            hydrationScore: Int(hydrationScore.rounded()),
            sheddingLevel: Int(sheddingLevel.rounded()),
            stressLevel: Int(stressLevel.rounded()),
            hasItch: hasItch,
            hasFlaking: hasFlaking,
            hasScalpPain: hasScalpPain,
            hasPatchyHairLoss: hasPatchyHairLoss,
            hasTightStyleTension: hasTightStyleTension,
            isWashDay: isWashDay,
            note: note.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty ? "Quick check-in logged." : note,
            dailyObservation: observation
        )
        observation.summary = checkInSummary(for: entry)
        modelContext.insert(entry)
        savePhotoRecordIfNeeded(for: entry, observation: observation)
        dismiss()
    }

    private func savePhotoRecordIfNeeded(for entry: CheckInEntry, observation: DailyObservation) {
        guard let checkInPhoto else { return }

        do {
            let dayStart = Calendar.current.startOfDay(for: date)
            let nextDay = Calendar.current.date(byAdding: .day, value: 1, to: dayStart) ?? dayStart
            let descriptor = FetchDescriptor<PhotoRecord>(
                predicate: #Predicate<PhotoRecord> {
                    $0.checkIn != nil && $0.createdAt >= dayStart && $0.createdAt < nextDay
                }
            )
            let existingRecords = try modelContext.fetch(descriptor)
            existingRecords.forEach(modelContext.delete)

            let path = try PhotoFileStore.shared.save(image: checkInPhoto)
            let record = PhotoRecord(
                createdAt: date,
                sessionTitle: "Check-In \(date.formatted(date: .abbreviated, time: .omitted))",
                angle: "Check-In",
                imagePath: path,
                notes: photoNote.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty ? note : photoNote,
                checkIn: entry,
                dailyObservation: observation
            )
            modelContext.insert(record)
        } catch {
            return
        }
    }

    private func dailyObservation(for date: Date) -> DailyObservation {
        let dayStart = Calendar.current.startOfDay(for: date)
        let nextDay = Calendar.current.date(byAdding: .day, value: 1, to: dayStart) ?? dayStart
        let descriptor = FetchDescriptor<DailyObservation>(
            predicate: #Predicate<DailyObservation> {
                $0.date >= dayStart && $0.date < nextDay
            }
        )

        if let observation = try? modelContext.fetch(descriptor).first {
            return observation
        }

        let observation = DailyObservation(date: dayStart)
        modelContext.insert(observation)
        return observation
    }

