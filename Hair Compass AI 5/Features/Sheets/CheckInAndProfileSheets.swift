    private var logReferenceBand: some View {
        VStack(spacing: 6) {
            GeometryReader { geo in
                let width = geo.size.width
                ZStack(alignment: .leading) {
                    // Gradient band: teal→gold→rust
                    RoundedRectangle(cornerRadius: 5)
                        .fill(
                            LinearGradient(
                                colors: [
                                    PremiumTheme.teal,
                                    PremiumTheme.gold,
                                    Color(red: 0.75, green: 0.35, blue: 0.25)
                                ],
                                startPoint: .leading,
                                endPoint: .trailing
                            )
                        )
                        .frame(height: 10)

                    // Position marker
                    let fraction = min(CGFloat(sheddingCount) / 200.0, 1.0)
                    Circle()
                        .fill(Color.white)
                        .frame(width: 16, height: 16)
                        .shadow(color: .black.opacity(0.2), radius: 4, y: 2)
                        .offset(x: fraction * (width - 16))
                        .animation(.spring(response: 0.3, dampingFraction: 0.8), value: sheddingCount)
                }
            }
            .frame(height: 16)

            HStack {
                Text("LOW")
                    .font(.system(size: 9, weight: .bold, design: .monospaced))
                    .foregroundStyle(PremiumTheme.teal)
                Spacer()
                Text("MODERATE")
                    .font(.system(size: 9, weight: .bold, design: .monospaced))
                    .foregroundStyle(PremiumTheme.gold)
                Spacer()
                Text("HIGH")
                    .font(.system(size: 9, weight: .bold, design: .monospaced))
                    .foregroundStyle(Color(red: 0.75, green: 0.35, blue: 0.25))
            }
        }
        .padding(.horizontal, 4)
    }

    private func mapSheddingCountToLevel(_ count: Int) -> Int {
        // Map strand count (0-200) to the app's 0-100 shedding level scale
        switch count {
        case 0...20: return 10
        case 21...40: return 25
        case 41...60: return 40
        case 61...80: return 55
        case 81...100: return 65
        case 101...130: return 75
        case 131...160: return 85
        default: return 95
        }
    }
}

// Simple flow layout for trigger chips
struct FlowLayout: Layout {
    var spacing: CGFloat = 8

    func sizeThatFits(proposal: ProposedViewSize, subviews: Subviews, cache: inout ()) -> CGSize {
        let containerWidth = proposal.width ?? .infinity
        var currentX: CGFloat = 0
        var currentY: CGFloat = 0
        var lineHeight: CGFloat = 0

        for subview in subviews {
            let size = subview.sizeThatFits(.unspecified)
            if currentX + size.width > containerWidth && currentX > 0 {
                currentX = 0
                currentY += lineHeight + spacing
                lineHeight = 0
            }
            lineHeight = max(lineHeight, size.height)
            currentX += size.width + spacing
        }

        return CGSize(width: containerWidth, height: currentY + lineHeight)
    }

    func placeSubviews(in bounds: CGRect, proposal: ProposedViewSize, subviews: Subviews, cache: inout ()) {
        var currentX: CGFloat = bounds.minX
        var currentY: CGFloat = bounds.minY
        var lineHeight: CGFloat = 0

        for subview in subviews {
            let size = subview.sizeThatFits(.unspecified)
            if currentX + size.width > bounds.maxX && currentX > bounds.minX {
                currentX = bounds.minX
                currentY += lineHeight + spacing
                lineHeight = 0
            }
            subview.place(at: CGPoint(x: currentX, y: currentY), proposal: .unspecified)
            lineHeight = max(lineHeight, size.height)
            currentX += size.width + spacing
        }
    }
}

