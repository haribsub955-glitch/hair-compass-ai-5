    private func analysisTint(for score: Int) -> Color {
        switch score {
        case 70...100:
            return Color(red: 0.22, green: 0.58, blue: 0.42)
        case 40..<70:
            return Color(red: 0.85, green: 0.58, blue: 0.20)
        default:
            return Color(red: 0.76, green: 0.34, blue: 0.28)
        }
    }

    private func aiVerdict(for score: Int) -> String {
        switch score {
        case 70...100:
            return "Likely worth tracking"
